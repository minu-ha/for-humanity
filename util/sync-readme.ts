import {mkdir, readFile, writeFile} from "node:fs/promises";

/*
 * 이 저장소의 두 README를 기본 언어 홈과 한국어 홈에 동기화. 본문은 유지, 사이트용 링크만 변환
 *
 *   - 배포용 라이브러리에는 포함하지 않는 저장소 전용 작업
 *   - 영어 홈의 Korean 링크는 /ko/ 홈, 한국어 홈의 English 링크는 상대 README 그대로 루트 홈
 */
const source = await readFile(new URL("../README.md", import.meta.url), "utf8");

const content = source
    .replace('src="src/asset/favicon.svg"', 'src="/favicon.svg"')
    .replace('src="https://raw.githubusercontent.com/nomeehej/for-humanity/main/src/asset/favicon.svg"', 'src="/favicon.svg"')
    .replaceAll("](https://github.com/nomeehej/for-humanity/blob/main/content/public/", "](public/")
    .replaceAll("](content/public/", "](public/")
    .replaceAll("](LICENSE)", "](https://github.com/nomeehej/for-humanity/blob/main/LICENSE)")
    .replaceAll("](CHANGELOG.md)", "](https://github.com/nomeehej/for-humanity/blob/main/CHANGELOG.md)")
    .replaceAll("](https://github.com/nomeehej/for-humanity/blob/main/language/README.ko.md)", "](ko/README.md)")
    .replaceAll("](language/README.ko.md)", "](ko/README.md)");

await writeFile(new URL("../content/README.md", import.meta.url), `<!-- Generated by pnpm sync:readme from the repository README.md. -->\n\n${content}`);

const korean = (await readFile(new URL("../language/README.ko.md", import.meta.url), "utf8"))
    .replace('src="../src/asset/favicon.svg"', 'src="/favicon.svg"')
    .replaceAll("](../content/ko/public/", "](public/")
    .replaceAll("](../LICENSE)", "](https://github.com/nomeehej/for-humanity/blob/main/LICENSE)")
    .replaceAll("](../CHANGELOG.md)", "](https://github.com/nomeehej/for-humanity/blob/main/CHANGELOG.md)");

await mkdir(new URL("../content/ko/", import.meta.url), {recursive: true});
await writeFile(new URL("../content/ko/README.md", import.meta.url), `<!-- Generated by pnpm sync:readme from the repository language/README.ko.md. -->\n\n${korean}`);
