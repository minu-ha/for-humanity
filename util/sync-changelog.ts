import {readFile, writeFile} from "node:fs/promises";

/**
 * 공식 변경 기록의 사이트 문서 동기화 · npm에 포함하는 CHANGELOG.md를 원본으로 사용
 * 버전별 본문은 유지하고 문서 탐색 정보와 공개 릴리스 링크만 추가
 */
const source = await readFile(new URL("../CHANGELOG.md", import.meta.url), "utf8");
await writeFile(
    new URL("../templates/document/changelog.md", import.meta.url),
    `---\nname: Changelog\nlabel: 변경 기록\ngroup: Releases\norder: 10\n---\n\n<!-- Generated by pnpm sync:docs from the repository CHANGELOG.md. -->\n\n공식 버전별 변경 기록. npm 패키지에 포함되는 변경 기록과 같은 원본 사용.\n공개 버전과 패키지 파일은 [Releases](releases.md) · [GitHub Releases](https://github.com/minu-ha/for-humanity/releases)에서 확인.\n\n${source.replace(/^# Changelog\s*\n/, "").trim()}\n`,
);
